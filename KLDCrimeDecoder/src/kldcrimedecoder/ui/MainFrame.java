private static final Color BG    = new Color(0x0B1220);
private static final Color AMBER = new Color(0xFFB000);
private static final Color TEXT  = new Color(0xE8E8E8);
/** Adds one screen to cardPanel under a name. */
private void addScreen(String name, JPanel panel) {
    panel.setBackground(BG);
    cardPanel.add(panel, name);
}

/** Switches to a screen. The top bar is hidden on the menu only. */
public void showCard(String name) {
    CardLayout cl = (CardLayout) cardPanel.getLayout();
    cl.show(cardPanel, name);
    pnlTopBar.setVisible(!name.equals("menu"));
}

/** Updates the timer label (called by TimerManager in Phase 2). */
public void setTimerText(int secondsLeft) {
    int m = secondsLeft / 60;
    int s = secondsLeft % 60;
    lblTimer.setText(String.format("Time before the bell rings: %02d:%02d", m, s));
}

/** Updates the score label (called by ScoreManager in Phase 2). */
public void setScoreText(int score) {
    lblScore.setText("Score: " + score);
}

