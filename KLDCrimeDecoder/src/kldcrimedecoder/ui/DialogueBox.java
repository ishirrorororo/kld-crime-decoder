/** Plays {speaker, text} lines one by one. onFinished can be null. */
public void play(String[][] lines, Runnable onFinished) {
    hideBox();                                   // stop anything that was playing
    this.queue = lines;
    this.queueIndex = 0;
    this.onFinished = onFinished;
    setVisible(true);
    if (lines == null || lines.length == 0) {
        finish();
        return;
    }
    showLine(lines[0][0], lines[0][1]);
}

/** One line. Example: say("Arnie", "Hmm."); */
public void say(String speaker, String text) {
    play(new String[][] { { speaker, text } }, null);
}

/**
 * Shows a line AND a box of choices. onPick gets the number of the
 * option the player clicked (0 for the first one).
 */
public void ask(String speaker, String prompt, String[] options, IntConsumer onPick) {
    hideBox();
    choosing = true;
    setVisible(true);
    showLine(speaker, prompt);
    buildChoices(options, onPick);
}

/** Closes the box without running onFinished. */
public void hideBox() {
    typeTimer.stop();
    queue = null;
    onFinished = null;
    choosing = false;
    pnlChoices.removeAll();
    setVisible(false);
}

public boolean isOpen() {
    return isVisible();
}
/** Thin light line, a dark gap, then a second thin line. */
private static Border frame() {
    return BorderFactory.createCompoundBorder(
            BorderFactory.createLineBorder(EDGE_OUT, 1),
            BorderFactory.createCompoundBorder(
                    BorderFactory.createLineBorder(PANEL_BG, 3),
                    BorderFactory.createLineBorder(EDGE_IN, 1)));
}

