/** Starts typing one line. */
private void showLine(String speaker, String text) {
    boolean hasName = speaker != null && !speaker.isEmpty();
    pnlName.setVisible(hasName);                 // narration has no name plate
    lblSpeaker.setText(hasName ? speaker : "");

    fullText = text == null ? "" : text;
    boolean slow = false;
    boolean dim = false;
    boolean again = true;
    while (again) {                              // read the tags at the start
        again = false;
        if (fullText.startsWith("{slow}")) {
            slow = true;
            again = true;
            fullText = fullText.substring(6).trim();
        } else if (fullText.startsWith("{dim}")) {
            dim = true;
            again = true;
            fullText = fullText.substring(5).trim();
        }
    }
    typeTimer.setDelay(slow ? 55 : 20);
    txaLine.setForeground(dim ? DIM : TEXT);

    shown = 0;
    txaLine.setText("");
    btnNext.setVisible(false);
    typeTimer.restart();
}

/** One tick of the typewriter. */
private void typeNext() {
    shown++;
    txaLine.setText(fullText.substring(0, Math.min(shown, fullText.length())));
    if (shown >= fullText.length()) {
        typeTimer.stop();
        btnNext.setVisible(!choosing);           // arrow = "click to continue"
    }
}

/** Click: first show the whole line, then go to the next one. */
private void advance() {
    if (choosing) {
        return;                                  // the player must pick an option
    }
    if (typeTimer.isRunning()) {
        typeTimer.stop();
        shown = fullText.length();
        txaLine.setText(fullText);
        btnNext.setVisible(true);
        return;
    }
    queueIndex++;
    if (queue != null && queueIndex < queue.length) {
        showLine(queue[queueIndex][0], queue[queueIndex][1]);
    } else {
        finish();
    }
}

private void finish() {
    Runnable done = onFinished;                  // save it, hideBox() clears it
    hideBox();
    if (done != null) {
        done.run();
    }
}

/** Builds the choice list. It sits right above the text box. */
private void buildChoices(String[] options, final IntConsumer onPick) {
    pnlChoices.removeAll();

    JPanel list = new JPanel(new GridLayout(0, 1, 0, 2));
    list.setBackground(PANEL_BG);
    list.setBorder(BorderFactory.createCompoundBorder(
            frame(), BorderFactory.createEmptyBorder(6, 6, 6, 6)));

    for (int i = 0; i < options.length; i++) {
        final int index = i;
        final JLabel opt = new JLabel(options[i]);
        opt.setFont(SERIF);
        opt.setForeground(TEXT);
        opt.setOpaque(true);
        opt.setBackground(PANEL_BG);
        opt.setBorder(BorderFactory.createEmptyBorder(4, 10, 4, 10));
        opt.setCursor(Cursor.getPredefinedCursor(Cursor.HAND_CURSOR));
        opt.addMouseListener(new MouseAdapter() {
            @Override
            public void mouseEntered(MouseEvent e) {
                opt.setBackground(HILITE);       // teal highlight on hover
            }

            @Override
            public void mouseExited(MouseEvent e) {
                opt.setBackground(PANEL_BG);
            }

            @Override
            public void mousePressed(MouseEvent e) {
                hideBox();
                if (onPick != null) {
                    onPick.accept(index);
                }
            }
        });
        list.add(opt);
    }
    pnlChoices.add(list, BorderLayout.SOUTH);    // grows upward from the text box
    pnlChoices.revalidate();
    pnlChoices.repaint();
}

