/** Resets the screen and plays the intro. */
private void startLevel() {
    opened.clear();
    choiceStarted = false;
    boardActive = false;

    lblTitle.setText(Story.BOARD_TITLE);
    setFeedback("");
    pnlPhone.setVisible(false);
    buildBoard();

    // Sfx.play("footsteps");   // see the optional Sfx step from Level 3
    // Sfx.play("chatter");
    speak(withTime(Story.BOARD_INTRO), () -> {
        boardActive = true;
        setFeedback(Story.BOARD_TAP);
    });
}

/** Pins one card for each suspect. */
private void buildBoard() {
    pnlBoard.removeAll();
    cards = new JLabel[Story.BOARD_CARDS.length];
    for (int i = 0; i < cards.length; i++) {
        cards[i] = makeCard(i, Story.BOARD_CARDS[i]);
        pnlBoard.add(cards[i]);
    }
    pnlBoard.revalidate();
    pnlBoard.repaint();
}

/** One pinned card: portrait, name, and a short reason. */
private JLabel makeCard(final int index, String[] row) {
    final JLabel card = new JLabel(
            "<html><body style='width:128px'><div align='center'><b>" + row[0]
            + "</b><br><small>" + row[1] + "</small></div></body></html>",
            loadImage(portraitFile(row[0]), 100, 112, row[0]),
            SwingConstants.CENTER) {
        @Override
        protected void paintComponent(Graphics g) {
            super.paintComponent(g);
            Graphics2D g2 = (Graphics2D) g.create();   // draw the red pin on top
            g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
            g2.setColor(new Color(0xC0392B));
            g2.fillOval(getWidth() / 2 - 8, 5, 16, 16);
            g2.setColor(new Color(255, 255, 255, 150));
            g2.fillOval(getWidth() / 2 - 4, 8, 5, 5);
            g2.dispose();
        }
    };
    card.setOpaque(true);
    card.setBackground(PAPER);
    card.setForeground(INK);
    card.setFont(new Font("Georgia", Font.PLAIN, 13));
    card.setVerticalTextPosition(SwingConstants.BOTTOM);
    card.setHorizontalTextPosition(SwingConstants.CENTER);
    card.setIconTextGap(8);
    card.setCursor(java.awt.Cursor.getPredefinedCursor(java.awt.Cursor.HAND_CURSOR));
    styleCard(card, false, false);

    card.addMouseListener(new MouseAdapter() {
        @Override
        public void mouseEntered(MouseEvent e) {
            styleCard(card, opened.contains(index), true);
        }

        @Override
        public void mouseExited(MouseEvent e) {
            styleCard(card, opened.contains(index), false);
        }

        @Override
        public void mousePressed(MouseEvent e) {
            openClue(index);
        }
    });
    return card;
}

/** Brown outline normally, amber when hovered or already read. */
private void styleCard(JLabel card, boolean read, boolean hover) {
    Color edge = (hover || read) ? Theme.AMBER : BROWN;
    int thick = hover ? 3 : 2;
    card.setBorder(BorderFactory.createCompoundBorder(
            BorderFactory.createLineBorder(edge, thick),
            BorderFactory.createEmptyBorder(26 - thick, 8 - thick, 8 - thick, 8 - thick)));
}

/** Tap a card: show its clue on the phone. */
private void openClue(int index) {
    if (!boardActive) {
        return;                                   // the intro or the choice is still going
    }
    String[] row = Story.BOARD_CARDS[index];
    lblPhoneApp.setText(row[2]);
    lblPhoneMeta.setText(row[3]);
    lblPhoneBody.setText("<html>" + row[4].replace("\n", "<br>") + "</html>");
    pnlPhone.setVisible(true);

    opened.add(index);
    styleCard(cards[index], true, false);
    if (opened.size() == Story.BOARD_CARDS.length) {
        setFeedback(Story.BOARD_ALL_READ);
    } else {
        setFeedback("Clues read: " + opened.size() + "/" + Story.BOARD_CARDS.length);
    }
}

/** All clues read: Arnie sums it up, then the player chooses. */
private void startChoice() {
    choiceStarted = true;
    boardActive = false;
    setFeedback("");
    speak(Story.BOARD_SUMMARY, this::askWho);
}

private void askWho() {
    DialogueBox box = GameManager.getDialogue();
    if (box == null) {                            // no dialogue box (testing the form alone)
        LevelManager.nextLevel();
        return;
    }
    TimerManager.pause();                         // the clock waits while the player chooses
    box.ask("", Story.BOARD_WHO, Story.BOARD_OPTIONS, pick -> {
        GameState gs = GameState.getInstance();
        if (!gs.isGameOver()) {
            TimerManager.resume();
        }
        gs.putChoice("board.firstPick", Story.BOARD_CARDS[pick][0]);
        if (pick == 0) {
            LevelManager.nextLevel();             // Amy: Level 5
        } else {
            // first build: the order is fixed, so Amy still comes first
            speak(Story.BOARD_FIXED_ORDER, () -> LevelManager.nextLevel());
        }
    });
}

/** Copies the lines and puts the real time left in place of {min}. */
private String[][] withTime(String[][] lines) {
    int secs = GameState.getInstance().getTimeLeftSeconds();
    int min = Math.max(1, (secs + 59) / 60);
    String words = min + (min == 1 ? " minute" : " minutes");
    String[][] copy = new String[lines.length][];
    for (int i = 0; i < lines.length; i++) {
        copy[i] = new String[] { lines[i][0], lines[i][1].replace("{min}", words) };
    }
    return copy;
}

/** Plays lines in the dialogue box. "after" runs when the last line ends. */
private void speak(String[][] lines, Runnable after) {
    DialogueBox box = GameManager.getDialogue();
    if (box == null) {
        if (after != null) {
            after.run();
        }
        return;
    }
    box.play(lines, after);
}

/** "Amy Mercado" becomes "portrait_amy_mercado.png". */
private static String portraitFile(String name) {
    return "portrait_" + name.toLowerCase().replace(' ', '_') + ".png";
}

/** Loads /kldcrimedecoder/images/<file>. If missing, draws a colored placeholder with a label. */
private static Icon loadImage(String file, int w, int h, String label) {
    java.net.URL url = SuspectBoard.class.getResource("/kldcrimedecoder/images/" + file);
    if (url != null) {
        Image img = new ImageIcon(url).getImage().getScaledInstance(w, h, Image.SCALE_SMOOTH);
        return new ImageIcon(img);
    }
    BufferedImage ph = new BufferedImage(w, h, BufferedImage.TYPE_INT_RGB);
    Graphics2D g = ph.createGraphics();
    g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
    g.setColor(new Color(0x4A5A6A));
    g.fillRect(0, 0, w, h);
    g.setColor(Theme.AMBER);
    g.drawRect(0, 0, w - 1, h - 1);
    g.setFont(new Font("Consolas", Font.PLAIN, 11));
    FontMetrics fm = g.getFontMetrics();
    g.drawString(label, Math.max(2, (w - fm.stringWidth(label)) / 2), h / 2);
    g.dispose();
    return new ImageIcon(ph);
}

